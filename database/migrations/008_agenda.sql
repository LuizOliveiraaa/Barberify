-- Domínio H — Agenda e agendamentos (6 tabelas).
-- Ligações sem FK, por ordem de dependência: agendamentos.fidelidade_assinatura_id,
-- agendamentos.lista_espera_id e lista_espera.agendamento_id (ciclo).

CREATE TABLE `agendamentos` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `empresa_id` BIGINT UNSIGNED NOT NULL,
  `unidade_id` BIGINT UNSIGNED NOT NULL,
  `profissional_id` BIGINT UNSIGNED NOT NULL,
  `cliente_id` BIGINT UNSIGNED NOT NULL,
  `codigo` VARCHAR(12) NOT NULL,
  `grupo_id` CHAR(26) NULL,
  `origem` VARCHAR(16) NOT NULL DEFAULT 'painel',
  `status` VARCHAR(24) NOT NULL DEFAULT 'pendente',
  `inicio` DATETIME NOT NULL,
  `fim` DATETIME NOT NULL,
  `duracao_total` SMALLINT UNSIGNED NOT NULL,
  `valor_servicos` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  `desconto` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  `valor_total` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  `valor_pago` DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  `observacoes` TEXT NULL,
  `reserva_token` CHAR(64) NULL,
  `reserva_expira_em` DATETIME NULL,
  `confirmado_em` DATETIME NULL,
  `confirmacao_ip` VARCHAR(45) NULL,
  `confirmacao_canal` VARCHAR(24) NULL,
  `requisicao_id` CHAR(36) NULL,
  `fidelidade_assinatura_id` BIGINT UNSIGNED NULL,
  `lista_espera_id` BIGINT UNSIGNED NULL,
  `cancelado_em` DATETIME NULL,
  `cancelado_por_tipo` VARCHAR(16) NULL,
  `motivo_cancelamento` VARCHAR(255) NULL,
  `concluido_em` DATETIME NULL,
  `criado_por_tipo` VARCHAR(16) NOT NULL DEFAULT 'empresa',
  `criado_por_id` BIGINT UNSIGNED NULL,
  `criado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `atualizado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_agendamentos_codigo` (`codigo`),
  UNIQUE KEY `uq_agendamentos_requisicao` (`requisicao_id`),
  KEY `idx_agendamentos_empresa_inicio` (`empresa_id`, `inicio`),
  KEY `idx_agendamentos_profissional_inicio` (`profissional_id`, `inicio`),
  KEY `idx_agendamentos_unidade_inicio` (`unidade_id`, `inicio`),
  KEY `idx_agendamentos_status` (`empresa_id`, `status`),
  KEY `idx_agendamentos_cliente` (`cliente_id`, `inicio`),
  KEY `idx_agendamentos_expira` (`reserva_expira_em`),
  CONSTRAINT `fk_agendamentos_empresa` FOREIGN KEY (`empresa_id`) REFERENCES `empresas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agendamentos_unidade` FOREIGN KEY (`unidade_id`) REFERENCES `unidades` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agendamentos_profissional` FOREIGN KEY (`profissional_id`) REFERENCES `profissionais` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agendamentos_cliente` FOREIGN KEY (`cliente_id`) REFERENCES `clientes` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `agendamento_servicos` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `empresa_id` BIGINT UNSIGNED NOT NULL,
  `agendamento_id` BIGINT UNSIGNED NOT NULL,
  `servico_id` BIGINT UNSIGNED NOT NULL,
  `profissional_id` BIGINT UNSIGNED NOT NULL,
  `ordem` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `nome_snapshot` VARCHAR(120) NOT NULL,
  `preco_snapshot` DECIMAL(12,2) NOT NULL,
  `duracao_snapshot` SMALLINT UNSIGNED NOT NULL,
  `comissao_tipo_snapshot` VARCHAR(12) NULL,
  `comissao_valor_snapshot` DECIMAL(12,2) NULL,
  `coberto_por_assinatura` TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_agendamento_servicos_agendamento` (`agendamento_id`),
  KEY `idx_agendamento_servicos_empresa` (`empresa_id`),
  CONSTRAINT `fk_agendamento_servico_empresa` FOREIGN KEY (`empresa_id`) REFERENCES `empresas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agendamento_servico_agendamento` FOREIGN KEY (`agendamento_id`) REFERENCES `agendamentos` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agendamento_servico_servico` FOREIGN KEY (`servico_id`) REFERENCES `servicos` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_agendamento_servico_profissional` FOREIGN KEY (`profissional_id`) REFERENCES `profissionais` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `agendamento_status_historico` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `empresa_id` BIGINT UNSIGNED NOT NULL,
  `agendamento_id` BIGINT UNSIGNED NOT NULL,
  `de` VARCHAR(24) NULL,
  `para` VARCHAR(24) NOT NULL,
  `motivo` VARCHAR(255) NULL,
  `ator_tipo` VARCHAR(16) NOT NULL DEFAULT 'sistema',
  `ator_id` BIGINT UNSIGNED NULL,
  `criado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_agendamento_historico` (`agendamento_id`, `criado_em`),
  CONSTRAINT `fk_agendamento_hist_empresa` FOREIGN KEY (`empresa_id`) REFERENCES `empresas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agendamento_hist_agendamento` FOREIGN KEY (`agendamento_id`) REFERENCES `agendamentos` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `agenda_bloqueios_concorrencia` (
  `profissional_id` BIGINT UNSIGNED NOT NULL,
  `data` DATE NOT NULL,
  `atualizado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`profissional_id`, `data`),
  CONSTRAINT `fk_agenda_trava_profissional` FOREIGN KEY (`profissional_id`) REFERENCES `profissionais` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `agenda_bloqueios` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `empresa_id` BIGINT UNSIGNED NOT NULL,
  `unidade_id` BIGINT UNSIGNED NOT NULL,
  `profissional_id` BIGINT UNSIGNED NULL,
  `inicio` DATETIME NOT NULL,
  `fim` DATETIME NOT NULL,
  `motivo` VARCHAR(160) NULL,
  `criado_por` BIGINT UNSIGNED NULL,
  `criado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_agenda_bloqueios_periodo` (`empresa_id`, `unidade_id`, `inicio`, `fim`),
  CONSTRAINT `fk_agenda_bloqueio_empresa` FOREIGN KEY (`empresa_id`) REFERENCES `empresas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agenda_bloqueio_unidade` FOREIGN KEY (`unidade_id`) REFERENCES `unidades` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agenda_bloqueio_profissional` FOREIGN KEY (`profissional_id`) REFERENCES `profissionais` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_agenda_bloqueio_usuario` FOREIGN KEY (`criado_por`) REFERENCES `usuarios_empresa` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `lista_espera` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `empresa_id` BIGINT UNSIGNED NOT NULL,
  `unidade_id` BIGINT UNSIGNED NOT NULL,
  `cliente_id` BIGINT UNSIGNED NOT NULL,
  `servico_id` BIGINT UNSIGNED NOT NULL,
  `profissional_id` BIGINT UNSIGNED NULL,
  `data_preferida` DATE NULL,
  `periodo` VARCHAR(12) NOT NULL DEFAULT 'qualquer',
  `prioridade` TINYINT UNSIGNED NOT NULL DEFAULT 5,
  `status` VARCHAR(16) NOT NULL DEFAULT 'aguardando',
  `tentativas` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `notificado_em` DATETIME NULL,
  `reserva_expira_em` DATETIME NULL,
  `agendamento_id` BIGINT UNSIGNED NULL,
  `expira_em` DATETIME NULL,
  `criado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `atualizado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_lista_espera_fila` (`empresa_id`, `status`, `prioridade`, `criado_em`),
  KEY `idx_lista_espera_cliente` (`cliente_id`),
  CONSTRAINT `fk_lista_espera_empresa` FOREIGN KEY (`empresa_id`) REFERENCES `empresas` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_lista_espera_unidade` FOREIGN KEY (`unidade_id`) REFERENCES `unidades` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_lista_espera_cliente` FOREIGN KEY (`cliente_id`) REFERENCES `clientes` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_lista_espera_servico` FOREIGN KEY (`servico_id`) REFERENCES `servicos` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_lista_espera_profissional` FOREIGN KEY (`profissional_id`) REFERENCES `profissionais` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
